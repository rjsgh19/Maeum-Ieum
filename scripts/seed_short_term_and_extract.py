def build_rows() -> list[dict]:
    rows: list[dict] = []
    for date_iso, lines in SECTIONS:
        day_start = datetime.fromisoformat(f"{date_iso}T09:00:00").replace(tzinfo=KST)
        for i, content in enumerate(lines):
            rows.append(
                {
                    "user_id": USER_ID,
                    "role": "user",
                    "content": content,
                    "chat_time": (day_start + timedelta(seconds=i)).isoformat(),
                    "is_extracted": False,
                }
            )
    return rows


def main() -> None:
    rows = build_rows()
    logger.info("삽입할 메시지: %d건 (user_id=%s)", len(rows), USER_ID)

    sb = get_supabase()
    batch_size = 40
    for i in range(0, len(rows), batch_size):
        chunk = rows[i : i + batch_size]
        sb.table("short_term_history").insert(chunk).execute()
        logger.info("short_term_history 삽입: %d~%d", i + 1, min(i + batch_size, len(rows)))

    async def _run_extract() -> None:
        extracted = await extract_memories(user_id=USER_ID, limit=max(200, len(rows) + 50))
        logger.info("장기기억 추출 완료: %d건", len(extracted))

    asyncio.run(_run_extract())


if __name__ == "__main__":
    main()
